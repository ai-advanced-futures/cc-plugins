"""NPV calculator for the monetize phase of strategic-partnerships.

Run: uv run ${CLAUDE_PLUGIN_ROOT}/scripts/npv_calculator.py <model.json> [--out FILE]
The file holds `cash_flows`, `discount_rate` and `program_cost`. The script prints `npv`,
`roi_multiple` (`npv / program_cost`) and `verdict`. A negative `roi_multiple` gives `NO_GO`.

Implements financial modeling: discounted cash flow NPV, ROI multiple,
and GO/CONDITIONAL_GO/NO_GO verdict assignment.

With `--out`, the script writes the result to the file and prints 1 line.
"""

import argparse
import json
import sys
from pathlib import Path


def calculate_npv(cash_flows: list[float], discount_rate: float) -> float:
    """Calculate net present value of a series of future cash flows.

    Args:
        cash_flows: Annual net cash flows starting from Year 1 (not Year 0).
        discount_rate: Annual discount rate as a decimal (e.g., 0.10 for 10%).
                       Must be strictly between 0 and 1 exclusive.

    Returns:
        NPV as a float (may be negative for loss-making partnerships).

    Raises:
        ValueError: If cash_flows is empty.
        ValueError: If discount_rate is not in (0, 1) exclusive.
    """
    if not cash_flows:
        raise ValueError("cash_flows must not be empty")
    if discount_rate <= 0 or discount_rate >= 1:
        raise ValueError(
            f"discount_rate must be strictly between 0 and 1, got {discount_rate}"
        )

    return sum(
        cf / (1 + discount_rate) ** t
        for t, cf in enumerate(cash_flows, start=1)
    )


def calculate_roi_multiple(total_return: float, total_investment: float) -> float:
    """Calculate the ROI multiple for a partnership.

    Args:
        total_return: Total return generated by the partnership.
        total_investment: Total investment cost. Must be strictly positive.

    Returns:
        ROI multiple as a float.

    Raises:
        ValueError: If total_investment is <= 0.
    """
    if total_investment <= 0:
        raise ValueError(
            f"total_investment must be strictly positive, got {total_investment}"
        )
    return total_return / total_investment


def assign_verdict(roi_multiple: float) -> str:
    """Assign a partnership verdict based on the ROI multiple.

    Args:
        roi_multiple: The ROI multiple from calculate_roi_multiple().
                      Must be >= 0 (negative values are data errors).

    Returns:
        "GO"             if roi_multiple >= 3.0
        "CONDITIONAL_GO" if 2.0 <= roi_multiple < 3.0
        "NO_GO"          if roi_multiple < 2.0

    Raises:
        ValueError: If roi_multiple is negative (data error).
    """
    if roi_multiple < 0:
        raise ValueError(
            f"roi_multiple must be >= 0 (negative ROI is a data error), got {roi_multiple}"
        )
    if roi_multiple >= 3.0:
        return "GO"
    if roi_multiple >= 2.0:
        return "CONDITIONAL_GO"
    return "NO_GO"


def evaluate_model(model: dict) -> dict:
    """Calculate `npv`, `roi_multiple` and `verdict` for one model."""
    if not isinstance(model, dict):
        raise ValueError("the file must hold an object")
    for key in ("cash_flows", "discount_rate", "program_cost"):
        if key not in model:
            raise ValueError(f"missing key: '{key}'")
    npv = calculate_npv(model["cash_flows"], model["discount_rate"])
    roi_multiple = calculate_roi_multiple(npv, model["program_cost"])
    verdict = "NO_GO" if roi_multiple < 0 else assign_verdict(roi_multiple)
    return {"npv": npv, "roi_multiple": roi_multiple, "verdict": verdict}


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.strip().splitlines()[0])
    parser.add_argument("input", help="path of the JSON file")
    parser.add_argument("--out", help="write the result to this file and print one line")
    args = parser.parse_args(argv)
    try:
        result = evaluate_model(json.loads(Path(args.input).read_text()))
        text = json.dumps(result, indent=2)
        if args.out:
            Path(args.out).write_text(text + "\n")
    except (OSError, ValueError, TypeError) as err:
        print(f"error: {err}", file=sys.stderr)
        return 1
    print(f"verdict={result['verdict']}" if args.out else text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
