@dataclass
class ValueMetrics:
    """Container for EVC value metrics."""
    time_savings: float = 0.0
    error_reduction: float = 0.0
    revenue_impact: float = 0.0
    risk_reduction: float = 0.0

    @property
    def total_value(self) -> float:
        """Calculate total monthly value."""
        return (self.time_savings + self.error_reduction +
                self.revenue_impact + self.risk_reduction)

    @property
    def annual_value(self) -> float:
        """Calculate total annual value."""
        return self.total_value * 12


def calculate_time_savings(
    hours_saved: float,
    hourly_rate: float = 75.0,
    frequency_per_month: int = 1
) -> float:
    """
    Calculate monthly value from time savings.

    Args:
        hours_saved: Hours saved per occurrence
        hourly_rate: Fully loaded hourly cost of employee
        frequency_per_month: How often the task occurs per month

    Returns:
        Monthly value in dollars
    """
    return hours_saved * hourly_rate * frequency_per_month


def calculate_error_reduction(
    errors_avoided: float,
    cost_per_error: float,
    frequency_per_month: int = 1
) -> float:
    """
    Calculate monthly value from error reduction.

    Args:
        errors_avoided: Number of errors avoided per occurrence
        cost_per_error: Cost impact of each error
        frequency_per_month: How often the task occurs per month

    Returns:
        Monthly value in dollars
    """
    return errors_avoided * cost_per_error * frequency_per_month


def calculate_revenue_impact(
    revenue_increase: float,
    margin: float = 0.3,
    probability: float = 0.5
) -> float:
    """
    Calculate monthly value from revenue impact.

    Args:
        revenue_increase: Expected monthly revenue increase
        margin: Profit margin on incremental revenue
        probability: Probability of achieving the increase

    Returns:
        Expected monthly value in dollars
    """
    return revenue_increase * margin * probability


def calculate_risk_reduction(
    risk_probability_reduction: float,
    cost_if_occurs: float
) -> float:
    """
    Calculate monthly value from risk reduction.

    Args:
        risk_probability_reduction: Reduction in monthly probability (e.g., 0.05 for 5%)
        cost_if_occurs: Cost if the risk materializes

    Returns:
        Monthly value in dollars
    """
    return risk_probability_reduction * cost_if_occurs


def calculate_value_to_price_ratio(
    total_value: float,
    monthly_price: float
) -> float:
    """
    Calculate the value-to-price ratio.

    Args:
        total_value: Total monthly value delivered
        monthly_price: Monthly subscription/license cost

    Returns:
        Ratio of value to price (higher is better)
    """
    if monthly_price <= 0:
        return float('inf')
    return total_value / monthly_price


def calculate_roi(
    annual_value: float,
    annual_cost: float
) -> float:
    """
    Calculate return on investment.

    Args:
        annual_value: Total annual value delivered
        annual_cost: Total annual cost (price + implementation + maintenance)

    Returns:
        ROI as a percentage
    """
    if annual_cost <= 0:
        return float('inf')
    return ((annual_value - annual_cost) / annual_cost) * 100


def compare_competitors(
    competitor_metrics: Dict[str, ValueMetrics],
    competitor_pricing: Dict[str, float]
) -> pd.DataFrame:
    """
    Compare value metrics across competitors.

    Args:
        competitor_metrics: Dict mapping competitor names to ValueMetrics
        competitor_pricing: Dict mapping competitor names to monthly prices

    Returns:
        DataFrame with comparison metrics
    """
    data = []

    for name, metrics in competitor_metrics.items():
        price = competitor_pricing.get(name, 0)
        row = {
            'Competitor': name,
            'Time Savings': metrics.time_savings,
            'Error Reduction': metrics.error_reduction,
            'Revenue Impact': metrics.revenue_impact,
            'Risk Reduction': metrics.risk_reduction,
            'Total Monthly Value': metrics.total_value,
            'Annual Value': metrics.annual_value,
            'Monthly Price': price,
            'Value/Price Ratio': calculate_value_to_price_ratio(metrics.total_value, price),
            'Annual ROI (%)': calculate_roi(metrics.annual_value, price * 12)
        }
        data.append(row)

    df = pd.DataFrame(data)
    return df.sort_values('Value/Price Ratio', ascending=False)


def sensitivity_analysis(
    base_metrics: ValueMetrics,
    variable: str,
    range_pct: float = 0.3,
    steps: int = 10
) -> pd.DataFrame:
    """
    Perform sensitivity analysis on a value component.

    Args:
        base_metrics: Baseline value metrics
        variable: Which component to vary ('time', 'error', 'revenue', 'risk')
        range_pct: Percentage range to vary (+/-)
        steps: Number of steps in the analysis

    Returns:
        DataFrame showing sensitivity results
    """
    variable_map = {
        'time': 'time_savings',
        'error': 'error_reduction',
        'revenue': 'revenue_impact',
        'risk': 'risk_reduction'
    }

    if variable not in variable_map:
        raise ValueError(f"Variable must be one of: {list(variable_map.keys())}")

    attr = variable_map[variable]
    base_value = getattr(base_metrics, attr)

    results = []
    for i in range(steps + 1):
        factor = 1 - range_pct + (2 * range_pct * i / steps)
        new_value = base_value * factor

        # Create modified metrics
        modified = ValueMetrics(
            time_savings=base_metrics.time_savings if attr != 'time_savings' else new_value,
            error_reduction=base_metrics.error_reduction if attr != 'error_reduction' else new_value,
            revenue_impact=base_metrics.revenue_impact if attr != 'revenue_impact' else new_value,
            risk_reduction=base_metrics.risk_reduction if attr != 'risk_reduction' else new_value,
        )

        results.append({
            'Factor': factor,
            f'{variable.title()} Value': new_value,
            'Total Value': modified.total_value,
            'Change (%)': ((modified.total_value - base_metrics.total_value) / base_metrics.total_value) * 100
        })

    return pd.DataFrame(results)


