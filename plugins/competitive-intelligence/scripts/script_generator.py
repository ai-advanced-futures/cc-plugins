"""
Script Generator for Competitive Intelligence Plugin.

This module generates executable Python scripts for:
- Value calculations (EVC metrics, ROI analysis)
- Visualizations (SWOT diagrams, performance charts, positioning maps)
- Update pipelines (refresh analysis, delta detection)
- Jupyter notebooks (interactive exploration)

All generated scripts are standalone and can be run independently.
"""

from dataclasses import dataclass, field
from enum import Enum
from pathlib import Path
from typing import Any, Dict, List, Optional


class ScriptType(Enum):
    """Types of scripts that can be generated."""
    VALUE_CALCULATOR = "value_calculator"
    VISUALIZATION = "visualization"
    UPDATE_PIPELINE = "update_pipeline"
    JUPYTER_NOTEBOOK = "jupyter_notebook"


@dataclass
class ScriptConfig:
    """Configuration for script generation."""
    script_type: ScriptType
    output_path: Path
    analysis_data: Dict[str, Any]
    include_comments: bool = True
    include_docstrings: bool = True


@dataclass
class GeneratedScript:
    """Result of script generation."""
    script_type: ScriptType
    filename: str
    content: str
    dependencies: List[str] = field(default_factory=list)
    description: str = ""


class ScriptGenerator:
    """
    Generates executable Python scripts from competitive intelligence analysis.

    The generator creates standalone scripts that can be run independently
    of the plugin, allowing users to customize and extend the analysis.
    """

    # Common dependencies for different script types
    DEPENDENCIES = {
        ScriptType.VALUE_CALCULATOR: ["pandas", "numpy"],
        ScriptType.VISUALIZATION: ["pandas", "numpy", "matplotlib", "seaborn"],
        ScriptType.UPDATE_PIPELINE: ["pandas", "json", "pathlib"],
        ScriptType.JUPYTER_NOTEBOOK: ["pandas", "numpy", "matplotlib", "seaborn", "IPython"],
    }

    def __init__(self, output_dir: Optional[Path] = None):
        """
        Initialize the script generator.

        Args:
            output_dir: Directory for generated scripts. Defaults to ./scripts/
        """
        self.output_dir = output_dir or Path("./scripts")

    def generate_all(self, analysis_data: Dict[str, Any]) -> List[GeneratedScript]:
        """
        Generate all script types from analysis data.

        Args:
            analysis_data: Complete analysis data from all phases

        Returns:
            List of generated scripts
        """
        scripts = []

        # Generate value calculator
        scripts.append(self.generate_value_calculator(analysis_data))

        # Generate visualization script
        scripts.append(self.generate_visualization(analysis_data))

        # Generate update pipeline
        scripts.append(self.generate_update_pipeline(analysis_data))

        # Generate requirements.txt
        scripts.append(self.generate_requirements())

        # Generate README
        scripts.append(self.generate_readme(analysis_data))

        return scripts

