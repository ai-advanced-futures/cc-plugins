def plot_performance_gaps(
    job_steps: List[str],
    your_scores: List[float],
    competitor_scores: Dict[str, List[float]],
    metric: str = "Speed",
    output_path: Optional[Path] = None
) -> plt.Figure:
    """
    Create a performance gap chart comparing job step scores.

    Args:
        job_steps: List of job step names
        your_scores: Your product's scores for each step
        competitor_scores: Dict mapping competitor names to their scores
        metric: What's being measured (Speed, Accuracy)
        output_path: Optional path to save the figure

    Returns:
        Matplotlib figure
    """
    fig, ax = plt.subplots(figsize=(12, 6))

    x = np.arange(len(job_steps))
    width = 0.8 / (len(competitor_scores) + 1)

    # Plot your scores
    bars = ax.bar(x - width * len(competitor_scores) / 2, your_scores,
                  width, label='Your Product', color='#2ecc71')

    # Plot competitor scores
    colors = ['#e74c3c', '#3498db', '#f39c12', '#9b59b6']
    for i, (name, scores) in enumerate(competitor_scores.items()):
        offset = width * (i + 1 - len(competitor_scores) / 2)
        ax.bar(x + offset, scores, width, label=name, color=colors[i % len(colors)])

    ax.set_xlabel('Job Steps')
    ax.set_ylabel(f'{metric} Score (1-5)')
    ax.set_title(f'Job Step {metric} Comparison')
    ax.set_xticks(x)
    ax.set_xticklabels(job_steps, rotation=45, ha='right')
    ax.legend()
    ax.set_ylim(0, 5.5)

    # Add gap annotations
    for i, step in enumerate(job_steps):
        your_score = your_scores[i]
        for name, scores in competitor_scores.items():
            gap = your_score - scores[i]
            if abs(gap) >= 2:
                color = 'green' if gap > 0 else 'red'
                ax.annotate(f'{gap:+.0f}', xy=(i, max(your_score, scores[i]) + 0.2),
                           ha='center', fontsize=8, color=color, fontweight='bold')

    plt.tight_layout()

    if output_path:
        fig.savefig(output_path, dpi=150, bbox_inches='tight')

    return fig


def plot_swot_quadrant(
    strengths: List[Tuple[str, float]],
    weaknesses: List[Tuple[str, float]],
    opportunities: List[Tuple[str, float]],
    threats: List[Tuple[str, float]],
    title: str = "SWOT Analysis",
    output_path: Optional[Path] = None
) -> plt.Figure:
    """
    Create a SWOT quadrant diagram.

    Args:
        strengths: List of (description, importance) tuples
        weaknesses: List of (description, importance) tuples
        opportunities: List of (description, importance) tuples
        threats: List of (description, importance) tuples
        title: Chart title
        output_path: Optional path to save the figure

    Returns:
        Matplotlib figure
    """
    fig, axes = plt.subplots(2, 2, figsize=(14, 10))

    quadrants = [
        (axes[0, 0], strengths, 'Strengths', '#2ecc71'),
        (axes[0, 1], weaknesses, 'Weaknesses', '#e74c3c'),
        (axes[1, 0], opportunities, 'Opportunities', '#3498db'),
        (axes[1, 1], threats, 'Threats', '#f39c12'),
    ]

    for ax, items, label, color in quadrants:
        ax.set_facecolor(color + '20')  # Light background
        ax.set_title(label, fontsize=14, fontweight='bold', color=color)
        ax.set_xlim(0, 10)
        ax.set_ylim(0, len(items) + 1)
        ax.axis('off')

        for i, (desc, importance) in enumerate(items[:5]):  # Top 5
            y = len(items) - i
            # Importance bar
            ax.barh(y, importance, height=0.6, color=color, alpha=0.7)
            # Text
            ax.text(0.2, y, f"{desc[:40]}..." if len(desc) > 40 else desc,
                   va='center', fontsize=9)
            ax.text(importance + 0.2, y, f"{importance:.1f}", va='center', fontsize=8)

    fig.suptitle(title, fontsize=16, fontweight='bold')
    plt.tight_layout()

    if output_path:
        fig.savefig(output_path, dpi=150, bbox_inches='tight')

    return fig


def plot_forces_diagram(
    push_score: float,
    pull_score: float,
    anxiety_score: float,
    habit_score: float,
    competitor_name: str = "Competitor",
    output_path: Optional[Path] = None
) -> plt.Figure:
    """
    Create a Forces of Progress diagram.

    Args:
        push_score: Strength of push forces (1-10)
        pull_score: Strength of pull forces (1-10)
        anxiety_score: Strength of anxiety forces (1-10)
        habit_score: Strength of habit forces (1-10)
        competitor_name: Name of the competitor
        output_path: Optional path to save the figure

    Returns:
        Matplotlib figure
    """
    fig, ax = plt.subplots(figsize=(10, 8))

    # Draw the central box
    ax.add_patch(plt.Rectangle((3, 3), 4, 4, fill=False, edgecolor='black', linewidth=2))
    ax.text(5, 5, 'Customer\\nDecision', ha='center', va='center', fontsize=12, fontweight='bold')

    # Push arrow (left, pointing right)
    ax.annotate('', xy=(3, 5), xytext=(0.5, 5),
                arrowprops=dict(arrowstyle='->', color='#2ecc71', lw=push_score/2))
    ax.text(0.3, 5.5, f'PUSH\\n{push_score:.1f}', ha='center', fontsize=10, color='#2ecc71')
    ax.text(0.3, 4.5, 'Pain with\\ncurrent', ha='center', fontsize=8)

    # Pull arrow (right, pointing left)
    ax.annotate('', xy=(7, 5), xytext=(9.5, 5),
                arrowprops=dict(arrowstyle='->', color='#3498db', lw=pull_score/2))
    ax.text(9.7, 5.5, f'PULL\\n{pull_score:.1f}', ha='center', fontsize=10, color='#3498db')
    ax.text(9.7, 4.5, f'Attraction to\\n{competitor_name}', ha='center', fontsize=8)

    # Anxiety arrow (bottom, pointing up)
    ax.annotate('', xy=(5, 3), xytext=(5, 0.5),
                arrowprops=dict(arrowstyle='->', color='#e74c3c', lw=anxiety_score/2))
    ax.text(5, 0.3, f'ANXIETY: {anxiety_score:.1f}', ha='center', fontsize=10, color='#e74c3c')
    ax.text(6.5, 1, 'Fear of\\nchange', ha='center', fontsize=8)

    # Habit arrow (top, pointing down)
    ax.annotate('', xy=(5, 7), xytext=(5, 9.5),
                arrowprops=dict(arrowstyle='->', color='#f39c12', lw=habit_score/2))
    ax.text(5, 9.7, f'HABIT: {habit_score:.1f}', ha='center', fontsize=10, color='#f39c12')
    ax.text(6.5, 9, 'Comfort with\\ncurrent', ha='center', fontsize=8)

    # Net calculation
    net_switch = (push_score + pull_score) - (anxiety_score + habit_score)
    color = '#2ecc71' if net_switch > 0 else '#e74c3c'
    ax.text(5, 1.8, f'Net Switching Pressure: {net_switch:+.1f}',
            ha='center', fontsize=11, fontweight='bold', color=color)

    ax.set_xlim(0, 10)
    ax.set_ylim(0, 10)
    ax.set_aspect('equal')
    ax.axis('off')
    ax.set_title(f'Forces Analysis: {competitor_name}', fontsize=14, fontweight='bold')

    if output_path:
        fig.savefig(output_path, dpi=150, bbox_inches='tight')

    return fig


def plot_positioning_map(
    positions: Dict[str, Tuple[float, float]],
    x_label: str = "Market Breadth",
    y_label: str = "Solution Depth",
    output_path: Optional[Path] = None
) -> plt.Figure:
    """
    Create a competitive positioning map.

    Args:
        positions: Dict mapping competitor names to (x, y) positions (0-1 scale)
        x_label: Label for x-axis
        y_label: Label for y-axis
        output_path: Optional path to save the figure

    Returns:
        Matplotlib figure
    """
    fig, ax = plt.subplots(figsize=(10, 10))

    colors = ['#2ecc71', '#e74c3c', '#3498db', '#f39c12', '#9b59b6', '#1abc9c']

    for i, (name, (x, y)) in enumerate(positions.items()):
        color = colors[i % len(colors)]
        ax.scatter(x, y, s=500, c=color, alpha=0.7, edgecolors='white', linewidth=2)
        ax.annotate(name, (x, y), xytext=(10, 10), textcoords='offset points',
                   fontsize=10, fontweight='bold')

    ax.set_xlim(-0.1, 1.1)
    ax.set_ylim(-0.1, 1.1)
    ax.set_xlabel(x_label, fontsize=12)
    ax.set_ylabel(y_label, fontsize=12)
    ax.set_title('Competitive Positioning Map', fontsize=14, fontweight='bold')

    # Add quadrant lines
    ax.axhline(y=0.5, color='gray', linestyle='--', alpha=0.5)
    ax.axvline(x=0.5, color='gray', linestyle='--', alpha=0.5)

    # Add quadrant labels
    ax.text(0.25, 0.95, 'Niche Deep', ha='center', fontsize=9, alpha=0.7)
    ax.text(0.75, 0.95, 'Broad Deep', ha='center', fontsize=9, alpha=0.7)
    ax.text(0.25, 0.05, 'Niche Shallow', ha='center', fontsize=9, alpha=0.7)
    ax.text(0.75, 0.05, 'Broad Shallow', ha='center', fontsize=9, alpha=0.7)

    if output_path:
        fig.savefig(output_path, dpi=150, bbox_inches='tight')

    return fig


def plot_value_comparison(
    competitors: List[str],
    values: List[float],
    prices: List[float],
    output_path: Optional[Path] = None
) -> plt.Figure:
    """
    Create a value vs price comparison chart.

    Args:
        competitors: List of competitor names
        values: List of monthly values
        prices: List of monthly prices
        output_path: Optional path to save the figure

    Returns:
        Matplotlib figure
    """
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(14, 6))

    x = np.arange(len(competitors))
    width = 0.35

    # Value vs Price bars
    ax1.bar(x - width/2, values, width, label='Monthly Value', color='#2ecc71')
    ax1.bar(x + width/2, prices, width, label='Monthly Price', color='#e74c3c')
    ax1.set_ylabel('Dollars ($)')
    ax1.set_title('Value vs Price Comparison')
    ax1.set_xticks(x)
    ax1.set_xticklabels(competitors, rotation=45, ha='right')
    ax1.legend()

    # Value/Price ratio
    ratios = [v/p if p > 0 else 0 for v, p in zip(values, prices)]
    colors = ['#2ecc71' if r > 5 else '#f39c12' if r > 3 else '#e74c3c' for r in ratios]
    ax2.bar(x, ratios, color=colors)
    ax2.set_ylabel('Value/Price Ratio')
    ax2.set_title('Value Efficiency (higher = better)')
    ax2.set_xticks(x)
    ax2.set_xticklabels(competitors, rotation=45, ha='right')
    ax2.axhline(y=5, color='green', linestyle='--', alpha=0.5, label='Good (5x)')
    ax2.axhline(y=3, color='orange', linestyle='--', alpha=0.5, label='Acceptable (3x)')
    ax2.legend()

    plt.tight_layout()

    if output_path:
        fig.savefig(output_path, dpi=150, bbox_inches='tight')

    return fig


