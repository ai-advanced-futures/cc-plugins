@dataclass
class ChangeRecord:
    """Record of a detected change."""
    competitor: str
    field: str
    previous_value: Any
    new_value: Any
    change_type: str  # 'added', 'removed', 'modified'
    significance: str  # 'high', 'medium', 'low'
    detected_at: str = ""

    def __post_init__(self):
        if not self.detected_at:
            self.detected_at = datetime.now().isoformat()


class AnalysisUpdater:
    """
    Manages updates to competitive intelligence analysis.
    """

    def __init__(self, analysis_dir: Path):
        """
        Initialize the updater.

        Args:
            analysis_dir: Directory containing analysis files
        """
        self.analysis_dir = Path(analysis_dir)
        self.history_dir = self.analysis_dir / "history"
        self.history_dir.mkdir(parents=True, exist_ok=True)

    def load_analysis(self, filename: str) -> Dict[str, Any]:
        """Load an analysis file."""
        path = self.analysis_dir / filename
        if path.exists():
            with open(path) as f:
                return json.load(f)
        return {}

    def save_analysis(self, filename: str, data: Dict[str, Any]):
        """Save an analysis file."""
        path = self.analysis_dir / filename
        with open(path, 'w') as f:
            json.dump(data, f, indent=2)

    def archive_current(self) -> Path:
        """
        Archive current analysis state before update.

        Returns:
            Path to archive directory
        """
        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        archive_dir = self.history_dir / timestamp
        archive_dir.mkdir(parents=True, exist_ok=True)

        # Copy all JSON files to archive
        for json_file in self.analysis_dir.glob("*.json"):
            if json_file.parent == self.analysis_dir:
                content = json_file.read_text()
                (archive_dir / json_file.name).write_text(content)

        return archive_dir

    def detect_changes(
        self,
        previous: Dict[str, Any],
        current: Dict[str, Any],
        path: str = ""
    ) -> List[ChangeRecord]:
        """
        Detect changes between previous and current analysis.

        Args:
            previous: Previous analysis data
            current: Current analysis data
            path: Current path in the data structure

        Returns:
            List of detected changes
        """
        changes = []

        # Check for removed keys
        for key in previous:
            if key not in current:
                changes.append(ChangeRecord(
                    competitor=path.split('.')[0] if path else 'global',
                    field=f"{path}.{key}" if path else key,
                    previous_value=previous[key],
                    new_value=None,
                    change_type='removed',
                    significance=self._assess_significance(key, previous[key], None)
                ))

        # Check for added/modified keys
        for key in current:
            current_path = f"{path}.{key}" if path else key

            if key not in previous:
                changes.append(ChangeRecord(
                    competitor=path.split('.')[0] if path else 'global',
                    field=current_path,
                    previous_value=None,
                    new_value=current[key],
                    change_type='added',
                    significance=self._assess_significance(key, None, current[key])
                ))
            elif isinstance(current[key], dict) and isinstance(previous[key], dict):
                # Recurse into nested dicts
                changes.extend(self.detect_changes(previous[key], current[key], current_path))
            elif current[key] != previous[key]:
                changes.append(ChangeRecord(
                    competitor=path.split('.')[0] if path else 'global',
                    field=current_path,
                    previous_value=previous[key],
                    new_value=current[key],
                    change_type='modified',
                    significance=self._assess_significance(key, previous[key], current[key])
                ))

        return changes

    def _assess_significance(
        self,
        field: str,
        old_value: Any,
        new_value: Any
    ) -> str:
        """Assess the significance of a change."""
        # High significance fields
        high_sig_fields = ['threat_level', 'tier', 'moat_score', 'disruption_risk']
        if any(f in field.lower() for f in high_sig_fields):
            return 'high'

        # Medium significance for score changes > 1
        if isinstance(old_value, (int, float)) and isinstance(new_value, (int, float)):
            if abs((new_value or 0) - (old_value or 0)) >= 2:
                return 'high'
            elif abs((new_value or 0) - (old_value or 0)) >= 1:
                return 'medium'

        return 'low'

    def generate_delta_report(
        self,
        changes: List[ChangeRecord]
    ) -> str:
        """
        Generate a human-readable delta report.

        Args:
            changes: List of detected changes

        Returns:
            Markdown-formatted report
        """
        report = ["# Competitive Intelligence Update Report\\n"]
        report.append(f"Generated: {datetime.now().isoformat()}\\n")

        # Group by significance
        high = [c for c in changes if c.significance == 'high']
        medium = [c for c in changes if c.significance == 'medium']
        low = [c for c in changes if c.significance == 'low']

        report.append(f"## Summary\\n")
        report.append(f"- High significance changes: {len(high)}")
        report.append(f"- Medium significance changes: {len(medium)}")
        report.append(f"- Low significance changes: {len(low)}\\n")

        if high:
            report.append("## High Significance Changes\\n")
            for change in high:
                report.append(f"### {change.competitor}: {change.field}")
                report.append(f"- Type: {change.change_type}")
                report.append(f"- Previous: {change.previous_value}")
                report.append(f"- Current: {change.new_value}\\n")

        if medium:
            report.append("## Medium Significance Changes\\n")
            for change in medium:
                report.append(f"- **{change.competitor}**: {change.field} ({change.change_type})")

        return "\\n".join(report)

    def update_ecosystem(
        self,
        new_competitors: Optional[List[Dict]] = None,
        updated_classifications: Optional[Dict[str, Dict]] = None
    ) -> Tuple[Dict[str, Any], List[ChangeRecord]]:
        """
        Update the competitive ecosystem with new data.

        Args:
            new_competitors: New competitors to add
            updated_classifications: Updated classifications for existing competitors

        Returns:
            Tuple of (updated ecosystem, list of changes)
        """
        # Load current ecosystem
        ecosystem = self.load_analysis("competitive-ecosystem.json")
        previous = json.loads(json.dumps(ecosystem))  # Deep copy

        # Add new competitors
        if new_competitors:
            competitors = ecosystem.get("competitors", [])
            existing_ids = {c.get("id") for c in competitors}
            for comp in new_competitors:
                if comp.get("id") not in existing_ids:
                    competitors.append(comp)
            ecosystem["competitors"] = competitors

        # Update classifications
        if updated_classifications:
            for comp_id, updates in updated_classifications.items():
                for comp in ecosystem.get("competitors", []):
                    if comp.get("id") == comp_id:
                        comp["classification"].update(updates)
                        break

        # Update timestamp
        ecosystem["updated_at"] = datetime.now().isoformat()

        # Detect changes
        changes = self.detect_changes(previous, ecosystem)

        return ecosystem, changes


